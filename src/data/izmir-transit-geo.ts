/**
 * İzmir Transit Geographic Data Module
 *
 * Real-world GPS coordinates for İzmir's transit network,
 * projected into a local Three.js coordinate system.
 *
 * Projection: Local Mercator centered on inner Gulf of İzmir
 *   x = east/west (positive = east)
 *   z = north/south (positive = south)
 *   y = elevation (negative = underground)
 *
 * Sources: OpenStreetMap, Wikipedia, İzmir Metropolitan Municipality
 */

import * as THREE from "three";

// === Projection parameters ===
const CENTER_LAT = 38.425;
const CENTER_LNG = 27.135;
const LNG_SCALE = 180; // scene units per degree of longitude
const LAT_SCALE = 230; // scene units per degree of latitude (adjusted for lat 38.4°)

/** Project WGS84 (lat, lng) to Three.js scene coordinates */
export function geoToScene(
  lat: number,
  lng: number,
  y = 0,
): THREE.Vector3 {
  return new THREE.Vector3(
    (lng - CENTER_LNG) * LNG_SCALE,
    y,
    (CENTER_LAT - lat) * LAT_SCALE,
  );
}

/** Project WGS84 to flat [x, z] tuple (for Shape / polygon ops) */
export function geoToFlat(lat: number, lng: number): [number, number] {
  return [
    (lng - CENTER_LNG) * LNG_SCALE,
    (CENTER_LAT - lat) * LAT_SCALE,
  ];
}

